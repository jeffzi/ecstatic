import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HEADER = "// Generated by scripts/sync-version.ts — do not edit.\n";

function readPackageVersion(projectRoot: string): string {
  const raw = readFileSync(join(projectRoot, "package.json"), "utf-8");
  const pkg: unknown = JSON.parse(raw);
  if (
    typeof pkg !== "object" ||
    pkg === null ||
    !("version" in pkg) ||
    typeof pkg.version !== "string"
  ) {
    throw new Error(`${join(projectRoot, "package.json")} is missing a string "version" field`);
  }
  return pkg.version;
}

function generateContent(version: string): string {
  return `${HEADER}/** The package's semver, synced from package.json at build time. */\nexport const VERSION: string = "${version}";\n`;
}

/**
 * Write `src/version.ts` from the version in `package.json`. Idempotent.
 *
 * @param projectRoot - Directory holding `package.json` and `src/`; the CLI passes
 * `process.cwd()`.
 * @throws Error when `package.json` has no string `version` field; a read or write failure
 * propagates as the filesystem error itself.
 */
export function syncVersion(projectRoot: string): void {
  const version = readPackageVersion(projectRoot);
  const content = generateContent(version);
  writeFileSync(join(projectRoot, "src", "version.ts"), content);
}

/**
 * Verify that `src/version.ts` matches `package.json`.
 *
 * @param projectRoot - Directory holding `package.json` and `src/`; the CLI passes
 * `process.cwd()`.
 * @throws Error naming both versions when they differ, or when `package.json` has no string
 * `version` field; a missing `src/version.ts` propagates as the read error itself.
 */
export function checkVersion(projectRoot: string): void {
  const packageVersion = readPackageVersion(projectRoot);
  const expected = generateContent(packageVersion);

  const versionPath = join(projectRoot, "src", "version.ts");
  const actual = readFileSync(versionPath, "utf-8");

  if (actual !== expected) {
    const fileMatch = /VERSION:\s*string\s*=\s*"([^"]*)"/.exec(actual);
    const fileVersion = fileMatch?.[1] ?? "<unknown>";
    throw new Error(
      `src/version.ts has "${fileVersion}" but package.json has "${packageVersion}" — run: npx tsx scripts/sync-version.ts`,
    );
  }
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.includes("--check")) {
    checkVersion(process.cwd());
  } else {
    syncVersion(process.cwd());
  }
}
