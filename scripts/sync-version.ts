import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_PATH = "scripts/sync-version.ts";
const HEADER = `// Generated by ${SCRIPT_PATH} — do not edit.\n`;
const TS_VERSION_FILE = "src/version.ts";
const GO_VERSION_FILE = "optimizer/internal/version/version.go";

function readPackageVersion(projectRoot: string): string {
  const raw = readFileSync(join(projectRoot, "package.json"), "utf-8");
  const pkg: unknown = JSON.parse(raw);
  if (
    typeof pkg !== "object" ||
    pkg === null ||
    !("version" in pkg) ||
    typeof pkg.version !== "string"
  ) {
    throw new Error(`${join(projectRoot, "package.json")} is missing a string "version" field`);
  }
  return pkg.version;
}

function generateTsContent(version: string): string {
  return `${HEADER}/** The package's semver, synced from package.json at build time. */\nexport const VERSION: string = "${version}";\n`;
}

function generateGoContent(version: string): string {
  return [
    `// Code generated by ${SCRIPT_PATH}; DO NOT EDIT.`,
    "",
    "// Package version holds the plugin's release version.",
    "package version",
    "",
    "// Version is the package's semver; it must match package.json.",
    `const Version = "${version}"`,
    "",
  ].join("\n");
}

function versionFiles(version: string): { path: string; content: string; pattern: RegExp }[] {
  return [
    {
      path: TS_VERSION_FILE,
      content: generateTsContent(version),
      pattern: /VERSION:\s*string\s*=\s*"([^"]*)"/,
    },
    {
      path: GO_VERSION_FILE,
      content: generateGoContent(version),
      pattern: /const Version\s*=\s*"([^"]*)"/,
    },
  ];
}

/**
 * Write `src/version.ts` and `optimizer/internal/version/version.go` from the version in
 * `package.json`. Idempotent.
 *
 * @param projectRoot - Directory holding `package.json`, `src/`, and `optimizer/internal/version/`;
 * the CLI passes `process.cwd()`.
 * @throws Error when `package.json` has no string `version` field.
 * @throws SyntaxError when `package.json` is not valid JSON.
 * @throws The filesystem error itself when `package.json` cannot be read or a version file cannot
 * be written, propagated as is.
 */
export function syncVersion(projectRoot: string): void {
  const version = readPackageVersion(projectRoot);
  for (const { path, content } of versionFiles(version)) {
    writeFileSync(join(projectRoot, path), content);
  }
}

/**
 * Verify that `src/version.ts` and `optimizer/internal/version/version.go` match
 * `package.json`.
 *
 * @param projectRoot - Directory holding `package.json`, `src/`, and `optimizer/internal/version/`;
 * the CLI passes `process.cwd()`.
 * @throws Error naming the first file that differs and both versions, or when `package.json` has
 * no string `version` field.
 * @throws SyntaxError when `package.json` is not valid JSON.
 * @throws The filesystem error itself when `package.json` or a version file cannot be read (a
 * missing version file included), propagated as is.
 */
export function checkVersion(projectRoot: string): void {
  const packageVersion = readPackageVersion(projectRoot);

  for (const { path, content, pattern } of versionFiles(packageVersion)) {
    const actual = readFileSync(join(projectRoot, path), "utf-8");
    if (actual !== content) {
      const fileVersion = pattern.exec(actual)?.[1] ?? "<unknown>";
      throw new Error(
        `${path} has "${fileVersion}" but package.json has "${packageVersion}" — run: npx tsx ${SCRIPT_PATH}`,
      );
    }
  }
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.includes("--check")) {
    checkVersion(process.cwd());
  } else {
    syncVersion(process.cwd());
  }
}
