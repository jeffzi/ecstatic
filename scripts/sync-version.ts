import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { isEntryScript } from "./entry.js";

const SCRIPT_PATH = "scripts/sync-version.ts";
const HEADER = `// Generated by ${SCRIPT_PATH} — do not edit.\n`;
const VERSION_FILE = "src/version.ts";

function readPackageVersion(projectRoot: string): string {
  const raw = readFileSync(join(projectRoot, "package.json"), "utf8");
  const pkg: unknown = JSON.parse(raw);
  if (
    typeof pkg !== "object" ||
    pkg === null ||
    !("version" in pkg) ||
    typeof pkg.version !== "string"
  ) {
    throw new Error(`${join(projectRoot, "package.json")} is missing a string "version" field`);
  }
  return pkg.version;
}

function generateContent(version: string): string {
  return `${HEADER}/** The package's semver, synced from package.json by npm version. */\nexport const VERSION: string = "${version}";\n`;
}

/**
 * Write `src/version.ts` from the version in `package.json`. Idempotent.
 *
 * @param projectRoot - Directory holding `package.json` and `src/`; the CLI passes `process.cwd()`.
 * @throws Error when `package.json` has no string `version` field.
 * @throws SyntaxError when `package.json` is not valid JSON.
 * @throws The filesystem error itself when `package.json` cannot be read or `src/version.ts` cannot
 * be written, propagated as is.
 */
export function syncVersion(projectRoot: string): void {
  const version = readPackageVersion(projectRoot);
  writeFileSync(join(projectRoot, VERSION_FILE), generateContent(version));
}

/**
 * Verify that `src/version.ts` matches `package.json`.
 *
 * @param projectRoot - Directory holding `package.json` and `src/`; the CLI passes `process.cwd()`.
 * @throws Error naming `src/version.ts` and both versions when they differ, or when `package.json`
 * has no string `version` field.
 * @throws SyntaxError when `package.json` is not valid JSON.
 * @throws The filesystem error itself when `package.json` or `src/version.ts` cannot be read (a
 * missing file included), propagated as is.
 */
export function checkVersion(projectRoot: string): void {
  const packageVersion = readPackageVersion(projectRoot);

  const actual = readFileSync(join(projectRoot, VERSION_FILE), "utf8");
  if (actual !== generateContent(packageVersion)) {
    const fileVersion = /VERSION:\s*string\s*=\s*"([^"]*)"/.exec(actual)?.[1] ?? "<unknown>";
    throw new Error(
      `${VERSION_FILE} has "${fileVersion}" but package.json has "${packageVersion}" — run: npx tsx ${SCRIPT_PATH}`,
    );
  }
}

if (isEntryScript(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.includes("--check")) {
    checkVersion(process.cwd());
  } else {
    syncVersion(process.cwd());
  }
}
